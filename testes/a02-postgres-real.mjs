

import { readFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';


const { PGlite } = await (async () => {
  try {
    return await import('@electric-sql/pglite');
  } catch {
    const fora = process.env.PGLITE_PATH;
    if (!fora) {
      console.error(
        'PGlite não encontrado. Instale com "npm i @electric-sql/pglite" ou aponte\n' +
        'PGLITE_PATH para a pasta @electric-sql/pglite de uma instalação existente.',
      );
      process.exit(2);
    }
    return await import(pathToFileURL(join(fora, 'dist', 'index.js')).href);
  }
})();

const raiz = join(dirname(fileURLToPath(import.meta.url)), '..');
const ARQUIVO_SQL = join(raiz, 'supabase-seguranca-09-rate-limit-chat.sql');


function extrairFuncao() {
  const sql = readFileSync(ARQUIVO_SQL, 'utf8');
  const inicio = sql.indexOf('create or replace function public.consumir_cota_chat');
  if (inicio === -1) throw new Error('Não encontrei consumir_cota_chat no arquivo 09.');
  const fim = sql.indexOf('\n$$;', inicio);
  if (fim === -1) throw new Error('Não encontrei o fim do corpo da função.');
  return sql.slice(inicio, fim + 4);
}

// --- Placar ------------------------------------------------------------------
let passou = 0;
let falhou = 0;
function conferir(nome, condicao, detalhe = '') {
  if (condicao) {
    passou++;
    console.log(`  OK    ${nome}${detalhe ? ` — ${detalhe}` : ''}`);
  } else {
    falhou++;
    console.log(`  FALHA ${nome}${detalhe ? ` — ${detalhe}` : ''}`);
  }
}

const db = new PGlite();

await db.exec(`
  create table public.ia_mensagens (
    id         bigint generated by default as identity primary key,
    sessao_id  text,
    pergunta   text,
    ip         text,
    created_at timestamptz not null default now()
  );
  create index ia_mensagens_ip_created_idx on public.ia_mensagens (ip, created_at desc);
  create index ia_mensagens_created_idx    on public.ia_mensagens (created_at desc);
`);

await db.exec(extrairFuncao());
console.log('\nFunção consumir_cota_chat criada em PostgreSQL real.\n');

async function consumir(ip, { minuto = 8, hora = 60, global = 2000 } = {}) {
  const r = await db.query(
    'select * from public.consumir_cota_chat($1, $2, $3, $4, $5, $6)',
    [ip, '11111111-1111-1111-1111-111111111111', 'pergunta de teste', minuto, hora, global],
  );
  return r.rows[0];
}

const contarLinhas = async (ip) => {
  const r = await db.query('select count(*)::int as n from public.ia_mensagens where ip = $1', [ip]);
  return r.rows[0].n;
};

// ============================================================================
console.log('T1 — limite por minuto: com limite 3, a quarta é recusada');
// ============================================================================
{
  const ip = 'teste-minuto';
  const resultados = [];
  for (let i = 0; i < 6; i++) resultados.push((await consumir(ip, { minuto: 3 })).resultado);

  const liberadas = resultados.filter((r) => r === 'ok').length;
  const recusadas = resultados.filter((r) => r === 'limite_ip').length;
  const linhas = await contarLinhas(ip);

  conferir('exatamente 3 liberadas', liberadas === 3, `liberadas=${liberadas}`);
  conferir('as outras 3 recusadas', recusadas === 3, `recusadas=${recusadas}`);
  conferir('contador final == liberadas', linhas === liberadas, `linhas=${linhas}`);
  conferir('recusada NÃO grava linha', linhas === 3, `linhas=${linhas}`);
  conferir('ordem correta (ok,ok,ok,bloq,bloq,bloq)',
    resultados.join(',') === 'ok,ok,ok,limite_ip,limite_ip,limite_ip', resultados.join(','));
}

// ============================================================================
console.log('\nT2 — nenhuma vaga é consumida duas vezes');
// ============================================================================
{
  const ip = 'teste-vagas';
  const vistos = [];
  for (let i = 0; i < 5; i++) {
    const r = await consumir(ip, { minuto: 5 });
    if (r.resultado === 'ok') vistos.push(r.ip_minuto);
  }
  const unicos = new Set(vistos);
  conferir('cada requisição autorizada recebeu um número de vaga distinto',
    unicos.size === vistos.length, `vagas=${vistos.join(',')}`);
  conferir('a sequência de vagas é 1..5 sem buraco nem repetição',
    vistos.join(',') === '1,2,3,4,5', vistos.join(','));
}

// ============================================================================
console.log('\nT3 — o limite por IP é por IP, não global');
// ============================================================================
{
  for (let i = 0; i < 3; i++) await consumir('vizinho-A', { minuto: 3 });
  const bloqueadoA = (await consumir('vizinho-A', { minuto: 3 })).resultado;
  const liberadoB = (await consumir('vizinho-B', { minuto: 3 })).resultado;
  conferir('IP que estourou é bloqueado', bloqueadoA === 'limite_ip', bloqueadoA);
  conferir('IP vizinho segue liberado', liberadoB === 'ok', liberadoB);
}

// ============================================================================
console.log('\nT4 — teto global do projeto');
// ============================================================================
{
  const antes = (await db.query('select count(*)::int as n from public.ia_mensagens')).rows[0].n;
  const r = await consumir('teste-global', { minuto: 8, hora: 60, global: antes });
  conferir('estourado o teto global, recusa com limite_global',
    r.resultado === 'limite_global', r.resultado);
  conferir('a contagem global devolvida bate com a tabela',
    r.global_hora === antes, `devolvido=${r.global_hora} real=${antes}`);

  const depois = (await db.query('select count(*)::int as n from public.ia_mensagens')).rows[0].n;
  conferir('recusa global não gravou linha', depois === antes, `${antes} -> ${depois}`);
}

// ============================================================================
console.log('\nT5 — janela DESLIZANTE, não fixa');
// ============================================================================
{
  const ip = 'teste-janela';
  // Três mensagens com 90 segundos de idade: já saíram da janela de 1 minuto,
  // mas ainda estão dentro da janela de 1 hora.
  await db.query(
    `insert into public.ia_mensagens (sessao_id, pergunta, ip, created_at)
     select '00000000-0000-0000-0000-000000000000', 'antiga', $1, now() - interval '90 seconds'
     from generate_series(1, 3)`, [ip]);

  const r = await consumir(ip, { minuto: 3, hora: 60 });
  conferir('mensagens fora da janela de 1 min não contam para o limite do minuto',
    r.resultado === 'ok', r.resultado);
  conferir('mas continuam contando para a janela de 1 hora',
    r.ip_hora === 4, `ip_hora=${r.ip_hora}`);

  // Agora o limite por hora: já são 4 na hora, com limite 4 a próxima cai.
  const r2 = await consumir(ip, { minuto: 8, hora: 4 });
  conferir('limite por hora bloqueia mesmo com o do minuto livre',
    r2.resultado === 'limite_ip', r2.resultado);
}

// ============================================================================
console.log('\nT6 — fail-closed com parâmetros inválidos');
// ============================================================================
{
  for (const [nome, limites] of [
    ['limite de minuto nulo', { minuto: null, hora: 60, global: 2000 }],
    ['limite negativo', { minuto: -1, hora: 60, global: 2000 }],
    ['limite global nulo', { minuto: 8, hora: 60, global: null }],
  ]) {
    const antes = (await db.query('select count(*)::int as n from public.ia_mensagens')).rows[0].n;
    const r = await consumir('teste-failclosed', limites);
    const depois = (await db.query('select count(*)::int as n from public.ia_mensagens')).rows[0].n;
    conferir(`${nome} -> recusa em vez de liberar`, r.resultado !== 'ok', r.resultado);
    conferir(`${nome} -> não grava linha`, depois === antes);
  }
}

// ============================================================================
console.log('\nT7 — IP ausente cai num balde limitado, nunca em "sem limite"');
// ============================================================================
{
  const resultados = [];
  for (let i = 0; i < 4; i++) {
    resultados.push((await consumir('   ', { minuto: 2 })).resultado);
  }
  conferir('IP vazio é normalizado e continua sendo limitado',
    resultados.filter((r) => r === 'ok').length === 2, resultados.join(','));
  const n = await contarLinhas('desconhecido');
  conferir('as linhas foram gravadas sob o rótulo "desconhecido"', n === 2, `linhas=${n}`);
}

// ============================================================================
console.log(`\n${'='.repeat(62)}`);
console.log(`RESULTADO: ${passou} verificações passaram, ${falhou} falharam.`);
console.log('='.repeat(62));
await db.close();
process.exit(falhou === 0 ? 0 : 1);

// ============================================================================
// Divisão de "Não foi dessa vez" em duas fatias — testes em PostgreSQL real
// ----------------------------------------------------------------------------
// Roda supabase-resgate-estoque.sql (schema completo, 7 prêmios) e depois
// supabase-resgate-dividir-nao-foi-dessa-vez.sql em cima, dentro de uma
// instância PGlite (PostgreSQL 18 em WASM) — mesmo plpgsql, mesmo planejador.
//
// Confere: a divisão fica 20+20 preservando a soma de peso efetivo, a ordem
// fica espalhada (fatia nova no lado oposto), só a fatia original continua
// marcada como consolação, o RPC do giro funciona sem nenhuma alteração nele
// (sorteia e baixa estoque das duas fatias normalmente, e cai no fallback
// certo quando tudo mais zera), e a migration é idempotente.
//
// ATENÇÃO — dependência ausente do repo: supabase-resgate-estoque.sql nunca
// foi commitado no git (era arquivo solto) e sumiu do disco em 2026-09-10.
// Para rodar este teste de novo, recrie esse arquivo na raiz do projeto antes
// (o conteúdo dele está registrado na conversa que criou este teste) — sem
// ele, `readFileSync` abaixo falha com ENOENT.
// ============================================================================

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const { PGlite } = await import('@electric-sql/pglite');

const raiz = join(dirname(fileURLToPath(import.meta.url)), '..');
const db = new PGlite();

let passou = 0;
let falhou = 0;

function ok(nome, condicao, detalhe = '') {
  if (condicao) {
    passou += 1;
    console.log(`  ✓ ${nome}`);
  } else {
    falhou += 1;
    console.log(`  ✗ ${nome}${detalhe ? ` — ${detalhe}` : ''}`);
  }
}

const linhas = async (sql, params) => (await db.query(sql, params)).rows;
const uma = async (sql, params) => (await linhas(sql, params))[0];

// --- Schema base (igual ao harness de resgate-estoque.mjs) -----------------
async function prepararBase() {
  await db.exec(`
    create role anon;
    create role authenticated;

    create table public.resgate_funcionarios (
      id bigint generated by default as identity primary key,
      nome text not null,
      ativo boolean not null default true,
      created_at timestamptz not null default now()
    );

    create table public.resgate_premios (
      id bigint generated by default as identity primary key,
      nome text not null,
      rotulo text,
      rotulo_secundario text,
      peso integer not null default 1 check (peso >= 0),
      ativo boolean not null default true,
      ordem integer not null default 0,
      created_at timestamptz not null default now()
    );

    create table public.resgate_vouchers (
      id bigint generated by default as identity primary key,
      codigo text not null unique,
      usado boolean not null default false,
      created_at timestamptz not null default now(),
      usado_em timestamptz,
      participante_nome text,
      funcionario_id bigint references public.resgate_funcionarios (id) on delete set null,
      funcionario_nome text,
      premio_id bigint references public.resgate_premios (id) on delete set null,
      premio_nome text
    );

    create table public.teste_config (chave text primary key, valor boolean not null);
    insert into public.teste_config values ('rate_limit_ok', true), ('eh_admin', true);

    create or replace function public.consumir_rate_limit(p_acao text, p_limite integer, p_janela interval)
    returns boolean language sql as $fn$
      select valor from public.teste_config where chave = 'rate_limit_ok';
    $fn$;

    create or replace function public.eh_admin()
    returns boolean language sql as $fn$
      select valor from public.teste_config where chave = 'eh_admin';
    $fn$;

    insert into public.resgate_funcionarios (nome) values ('Responsável');
  `);
}

let contadorVoucher = 0;
async function novoVoucher() {
  contadorVoucher += 1;
  const codigo = `TST${String(contadorVoucher).padStart(7, '0')}`;
  await db.query('insert into public.resgate_vouchers (codigo) values ($1)', [codigo]);
  return codigo;
}
async function girarNovo() {
  return uma('select * from public.girar_roleta_resgate($1, $2, $3)', [
    'Fulano de Tal',
    await novoVoucher(),
    1,
  ]);
}

// ============================================================================
console.log('\n=== SETUP: 7 prêmios + RPCs ===');
await prepararBase();
await db.exec(readFileSync(join(raiz, 'supabase-resgate-estoque.sql'), 'utf8'));
ok('supabase-resgate-estoque.sql aplicou sem erro', true);

const antes = await uma("select id, quantidade_total, quantidade_disponivel, peso::float8 as peso from public.resgate_premios where nome = 'Não foi dessa vez' and eh_consolacao");
ok('antes da divisão: uma fatia só, 40 de estoque', Number(antes.quantidade_total) === 40 && Number(antes.quantidade_disponivel) === 40);

// ============================================================================
console.log('\n=== DIVISÃO ===');
await db.exec(readFileSync(join(raiz, 'supabase-resgate-dividir-nao-foi-dessa-vez.sql'), 'utf8'));

{
  const fatias = await linhas(
    "select id, ordem, peso::float8 as peso, quantidade_total, quantidade_disponivel, eh_consolacao from public.resgate_premios where nome = 'Não foi dessa vez' order by eh_consolacao desc",
  );
  ok('agora existem duas fatias de "Não foi dessa vez"', fatias.length === 2, `veio ${fatias.length}`);

  const original = fatias.find((f) => f.eh_consolacao);
  const nova = fatias.find((f) => !f.eh_consolacao);
  ok('a original continua marcada como consolação', !!original);
  ok('a nova NÃO é consolação (só uma pode ser)', !!nova && nova.eh_consolacao === false);
  ok('original: 20 de 20', Number(original?.quantidade_total) === 20 && Number(original?.quantidade_disponivel) === 20);
  ok('nova: 20 de 20', Number(nova?.quantidade_total) === 20 && Number(nova?.quantidade_disponivel) === 20);
  ok('as duas mantêm peso 0.7', Number(original?.peso) === 0.7 && Number(nova?.peso) === 0.7);

  const somaPesoEfetivo =
    Number(original.peso) * Number(original.quantidade_disponivel) +
    Number(nova.peso) * Number(nova.quantidade_disponivel);
  ok('soma do peso efetivo das duas = 28, igual a antes (0.7×40)', somaPesoEfetivo === 28, `veio ${somaPesoEfetivo}`);

  ok('a fatia nova fica na ordem 6 (lado oposto da original, ordem 2)', Number(nova.ordem) === 6, `veio ${nova.ordem}`);

  const total8 = await uma('select count(*)::int as n from public.resgate_premios where ativo');
  ok('agora são 8 fatias ativas no total', Number(total8.n) === 8, `veio ${total8.n}`);

  const r100 = await uma("select ordem from public.resgate_premios where nome = 'R$ 100'");
  ok('R$ 100 subiu de ordem 6 para ordem 7 (abriu espaço pra fatia nova)', Number(r100.ordem) === 7, `veio ${r100.ordem}`);
}

// ============================================================================
console.log('\n=== IDEMPOTÊNCIA ===');
await db.exec(readFileSync(join(raiz, 'supabase-resgate-dividir-nao-foi-dessa-vez.sql'), 'utf8'));
{
  const total = await uma("select count(*)::int as n from public.resgate_premios where nome = 'Não foi dessa vez'");
  ok('rodar a migration de novo não duplica a fatia nova', Number(total.n) === 2, `veio ${total.n}`);
}

// ============================================================================
console.log('\n=== A RPC continua funcionando sem nenhuma alteração nela ===');
{
  // Zera tudo, dá 5 de estoque pra cada fatia de "não foi" e mais nada,
  // pra forçar os giros a caírem só nelas duas.
  await db.exec("update public.resgate_premios set quantidade_disponivel = 0 where ativo and nome <> 'Não foi dessa vez'");
  await db.exec("update public.resgate_premios set quantidade_disponivel = 5 where nome = 'Não foi dessa vez'");

  const idsNaoFoi = new Set(
    (await linhas("select id from public.resgate_premios where nome = 'Não foi dessa vez'")).map((l) => Number(l.id)),
  );
  const idOriginal = Number((await uma("select id from public.resgate_premios where nome = 'Não foi dessa vez' and eh_consolacao")).id);

  let usouAsDuas = new Set();
  let erros = 0;
  for (let i = 0; i < 10; i++) {
    const r = await girarNovo();
    if (r.resultado !== 'sucesso') { erros += 1; continue; }
    if (!idsNaoFoi.has(Number(r.premio_id))) erros += 1;
    usouAsDuas.add(Number(r.premio_id));
  }
  ok('10 giros com só "não foi" disponível: todos deram sucesso e vieram das duas fatias', erros === 0);
  ok('as DUAS fatias (original e nova) foram sorteadas nesses 10 giros', usouAsDuas.size === 2, `só saiu de ${usouAsDuas.size}`);

  const estoqueRestante = await linhas("select id, quantidade_disponivel from public.resgate_premios where nome = 'Não foi dessa vez'");
  const totalConsumido = estoqueRestante.reduce((s, l) => s + (5 - Number(l.quantidade_disponivel)), 0);
  ok('estoque das duas fatias baixou normalmente (10 giros = 10 baixas)', totalConsumido === 10, `baixou ${totalConsumido}`);
  ok('nenhum estoque negativo', estoqueRestante.every((l) => Number(l.quantidade_disponivel) >= 0));

  // Zera as duas fatias de "não foi" também — agora TUDO no sistema está a 0.
  await db.exec("update public.resgate_premios set quantidade_disponivel = 0 where nome = 'Não foi dessa vez'");
  const fallback = await girarNovo();
  ok('com tudo zerado (inclusive as duas fatias), o fallback ainda responde', fallback.resultado === 'sucesso');
  ok('o fallback devolve a fatia ORIGINAL (a marcada como consolação)', Number(fallback.premio_id) === idOriginal);
  ok('o nome devolvido continua "Não foi dessa vez" (igual nas duas fatias)', fallback.premio_nome === 'Não foi dessa vez');
}

// ============================================================================
console.log(`\n=== RESULTADO: ${passou} passaram, ${falhou} falharam ===\n`);
await db.close();
process.exit(falhou === 0 ? 0 : 1);

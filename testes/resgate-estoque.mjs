// ============================================================================
// Estoque da campanha "Resgate seu Prêmio" — testes em PostgreSQL de verdade
// ----------------------------------------------------------------------------
// Roda supabase-resgate-estoque.sql dentro de uma instância PGlite
// (PostgreSQL 18 compilado para WASM). Não é mock: é o mesmo plpgsql, o mesmo
// planejador, o mesmo advisory lock.
//
// O QUE ESTE TESTE PROVA:      a migration produz os 7 prêmios com o estoque e
//                              os pesos combinados; o sorteio respeita
//                              peso × quantidade_disponivel; o estoque baixa uma
//                              unidade por giro e nunca fica negativo; prêmio
//                              esgotado ou com peso 0 nunca é sorteado; o
//                              fallback devolve "Não foi dessa vez" sem inflar
//                              estoque; voucher não se reutiliza.
//
// O QUE ESTE TESTE NÃO PROVA:  concorrência real. PGlite tem uma conexão só,
//                              então não existem duas transações simultâneas
//                              aqui. O que dá para verificar — e está no teste
//                              4 — é que a trava de estoque impede o segundo
//                              vencedor e que o advisory lock está no caminho.
//
// Como rodar (a dependência fica fora do projeto, package.json não é tocado):
//   npm i @electric-sql/pglite --prefix <pasta-temporaria>
//   NODE_PATH=<pasta-temporaria>/node_modules node testes/resgate-estoque.mjs
// ============================================================================

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const { PGlite } = await import('@electric-sql/pglite');

const raiz = join(dirname(fileURLToPath(import.meta.url)), '..');
const db = new PGlite();

let passou = 0;
let falhou = 0;

function ok(nome, condicao, detalhe = '') {
  if (condicao) {
    passou += 1;
    console.log(`  ✓ ${nome}`);
  } else {
    falhou += 1;
    console.log(`  ✗ ${nome}${detalhe ? ` — ${detalhe}` : ''}`);
  }
}

const linhas = async (sql, params) => (await db.query(sql, params)).rows;
const uma = async (sql, params) => (await linhas(sql, params))[0];

// --- Estado do banco antes da migration -------------------------------------
// Reproduz o schema criado por supabase-resgate-premio-setup.sql e os prêmios
// de teste que hoje estão em produção, para provar que a migration os tira da
// roleta sem apagá-los.
async function prepararBase() {
  await db.exec(`
    -- Papéis que o Supabase já traz prontos e que os GRANTs da migration citam.
    create role anon;
    create role authenticated;

    create table public.resgate_funcionarios (
      id bigint generated by default as identity primary key,
      nome text not null,
      ativo boolean not null default true,
      created_at timestamptz not null default now()
    );

    create table public.resgate_premios (
      id bigint generated by default as identity primary key,
      nome text not null,
      rotulo text,
      rotulo_secundario text,
      peso integer not null default 1 check (peso >= 0),
      ativo boolean not null default true,
      ordem integer not null default 0,
      created_at timestamptz not null default now()
    );

    create table public.resgate_vouchers (
      id bigint generated by default as identity primary key,
      codigo text not null unique,
      usado boolean not null default false,
      created_at timestamptz not null default now(),
      usado_em timestamptz,
      participante_nome text,
      funcionario_id bigint references public.resgate_funcionarios (id) on delete set null,
      funcionario_nome text,
      premio_id bigint references public.resgate_premios (id) on delete set null,
      premio_nome text
    );

    -- Stubs das dependências da série de segurança. O rate limit é controlado
    -- por uma tabelinha para o teste conseguir simular o limite estourado.
    create table public.teste_config (chave text primary key, valor boolean not null);
    insert into public.teste_config values ('rate_limit_ok', true), ('eh_admin', true);

    create or replace function public.consumir_rate_limit(p_acao text, p_limite integer, p_janela interval)
    returns boolean language sql as $fn$
      select valor from public.teste_config where chave = 'rate_limit_ok';
    $fn$;

    create or replace function public.eh_admin()
    returns boolean language sql as $fn$
      select valor from public.teste_config where chave = 'eh_admin';
    $fn$;

    insert into public.resgate_funcionarios (nome) values ('Responsável'), ('reponsavel2');

    insert into public.resgate_premios (nome, rotulo, rotulo_secundario, peso, ordem) values
      ('10% de desconto', '10%', 'DE DESCONTO', 1, 0),
      ('Mentoria', null, 'MENTORIA', 1, 1),
      ('20% de desconto', '20%', 'DE DESCONTO', 1, 2),
      ('TESTE', 'TT', 'TESTE', 1, 3),
      ('TESTE2', '2', 'TESTE', 1, 4),
      ('TESTE3', '3', 'TESTE', 1, 5);
  `);
}

// --- Utilitários do giro ----------------------------------------------------
let contadorVoucher = 0;

async function novoVoucher() {
  contadorVoucher += 1;
  const codigo = `TST${String(contadorVoucher).padStart(7, '0')}`;
  await db.query('insert into public.resgate_vouchers (codigo) values ($1)', [codigo]);
  return codigo;
}

async function girar(codigo, nome = 'Fulano de Tal', funcionarioId = 1) {
  return uma('select * from public.girar_roleta_resgate($1, $2, $3)', [nome, codigo, funcionarioId]);
}

async function girarNovo() {
  return girar(await novoVoucher());
}

const estoqueDe = async (nome) =>
  Number((await uma('select quantidade_disponivel from public.resgate_premios where nome = $1', [nome]))
    .quantidade_disponivel);

const zerarPesosExceto = async (nome) => {
  await db.query('update public.resgate_premios set peso = 0');
  await db.query('update public.resgate_premios set peso = 1 where nome = $1', [nome]);
};

const restaurarPesos = async () => {
  await db.exec(`
    update public.resgate_premios set peso = case nome
      when 'Pós-graduação / Superior Sequencial' then 1.5
      when 'Profissionalizantes' then 1.0
      when 'Não foi dessa vez' then 0.7
      when 'R$ 20' then 1.0
      when 'R$ 50' then 0.8
      when 'R$ 10' then 0.8
      when 'R$ 100' then 0.5
      else 0 end;
  `);
};

// ============================================================================
console.log('\n=== MIGRATION ===');
await prepararBase();
try {
  await db.exec(readFileSync(join(raiz, 'supabase-resgate-estoque.sql'), 'utf8'));
  ok('supabase-resgate-estoque.sql aplicou sem erro', true);
} catch (erro) {
  console.log(`  ✗ a migration falhou: ${erro.message}`);
  process.exit(1);
}

{
  const esperado = {
    'Pós-graduação / Superior Sequencial': [15, 1.5],
    Profissionalizantes: [150, 1.0],
    'Não foi dessa vez': [40, 0.7],
    'R$ 20': [15, 1.0],
    'R$ 50': [6, 0.8],
    'R$ 10': [100, 0.8],
    'R$ 100': [4, 0.5],
  };

  const campanha = await linhas(
    'select nome, peso::float8 as peso, quantidade_total, quantidade_disponivel, eh_consolacao, ordem from public.resgate_premios where ativo order by ordem',
  );

  ok('os 7 prêmios da campanha estão ativos', campanha.length === 7, `veio ${campanha.length}`);

  let estoquesCorretos = true;
  let pesosCorretos = true;
  for (const linha of campanha) {
    const alvo = esperado[linha.nome];
    if (!alvo) {
      estoquesCorretos = false;
      continue;
    }
    if (Number(linha.quantidade_total) !== alvo[0] || Number(linha.quantidade_disponivel) !== alvo[0]) {
      estoquesCorretos = false;
    }
    if (Number(linha.peso) !== alvo[1]) pesosCorretos = false;
  }
  ok('estoque de cada prêmio bate com a tabela combinada', estoquesCorretos);
  ok('pesos iniciais batem com a tabela combinada', pesosCorretos);

  const total = campanha.reduce((s, l) => s + Number(l.quantidade_total), 0);
  ok('estoque total é 330', total === 330, `veio ${total}`);

  const consolacao = campanha.filter((l) => l.eh_consolacao);
  ok(
    'só "Não foi dessa vez" está marcado como consolação',
    consolacao.length === 1 && consolacao[0].nome === 'Não foi dessa vez',
  );

  const antigos = await linhas("select nome, ativo, peso::float8 as peso from public.resgate_premios where nome like 'TESTE%' or nome = 'Mentoria'");
  ok('prêmios de teste continuam existindo (ids preservados)', antigos.length === 4, `veio ${antigos.length}`);
  ok('prêmios de teste saíram da roleta', antigos.every((l) => l.ativo === false && Number(l.peso) === 0));

  const decimal = await uma("select peso::text as peso from public.resgate_premios where nome = 'Pós-graduação / Superior Sequencial'");
  ok('peso aceita casas decimais', Number(decimal.peso) === 1.5, `veio ${decimal.peso}`);
}


-- ----------------------------------------------------------------------------
-- O PROBLEMA (medido em produção, não suposto)
--
-- `enviar_matricula` tem limite de 5 chamadas por hora por IP. Sete chamadas
-- seguidas do mesmo IP passaram todas. O mesmo com `girar_roleta_resgate`
-- (limite 10): doze chamadas, nenhuma barrada.
--
-- Como `enviar_matricula` é uma função nova, criada pelo arquivo 03, e ela
-- obrigatoriamente chama `consumir_rate_limit` na primeira linha, a conclusão
-- é que `consumir_rate_limit` está devolvendo `true` sempre.
--
-- SENDO HONESTO SOBRE O DIAGNÓSTICO
--
-- Não consigo consultar seu banco, então não sei qual dos candidatos abaixo é
-- o culpado. Este arquivo faz duas coisas: a PARTE 1 mostra o que está
-- acontecendo (e a saída me diz a causa exata), e a PARTE 2 reescreve a função
-- de um jeito que elimina os três candidatos de uma vez.
--
-- Candidatos:
--
--   (a) `force row level security` na tabela de contadores, somado a zero
--       policies. FORCE faz a RLS valer até para o dono da tabela. Se o papel
--       que executa a função não tiver BYPASSRLS, o `returning` do upsert pode
--       não devolver linha nenhuma — e aí a contagem vira NULL. Como
--       `NULL <= 5` é NULL, e `if not NULL` não entra no ramo, o limite nunca
--       dispara. Falha silenciosa, exatamente o sintoma observado.
--
--   (b) A referência `public.seguranca_rate_limit.contagem` dentro do
--       `on conflict do update`. Ali o certo é usar só o nome da tabela; a
--       forma qualificada com o schema pode não resolver.
--
--   (c) `identidade_requisicao()` devolvendo um valor diferente a cada
--       chamada, o que faria cada requisição criar uma linha nova em vez de
--       incrementar a existente.
--
-- A PARTE 2 troca o upsert por "uma linha por evento + contagem em janela
-- deslizante", que é mais simples, não depende de `on conflict`, não depende do
-- `returning`, e ainda melhora o comportamento: a janela passa a ser deslizante
-- de verdade, em vez de zerar de hora cheia em hora cheia.
--
-- PRÉ-REQUISITO: arquivos 01 a 04 já rodados.
-- ============================================================================


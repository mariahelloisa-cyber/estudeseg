-- PARTE 2 — CORREÇÃO
-- ###########################################################################

-- 2.1 Tabela nova: uma linha por evento, sem upsert.
drop table if exists public.seguranca_rate_limit;

create table public.seguranca_rate_limit (
  id          bigint generated by default as identity primary key,
  chave       text        not null,
  identidade  text        not null,
  ocorrido_em timestamptz not null default now()
);

comment on table public.seguranca_rate_limit is
  'Um registro por tentativa, para contagem em janela deslizante. Escrita só por '
  'funções SECURITY DEFINER; nenhum papel público tem acesso.';

create index seguranca_rate_limit_busca_idx
  on public.seguranca_rate_limit (chave, identidade, ocorrido_em desc);

revoke all on public.seguranca_rate_limit from anon, authenticated;
alter table public.seguranca_rate_limit enable row level security;

-- Sem `force`: a RLS continua barrando anon e authenticated (que nem GRANT
-- têm), mas para de atrapalhar a própria função que precisa gravar ali.
-- Esta é a diferença que resolve o candidato (a).
alter table public.seguranca_rate_limit no force row level security;

-- 2.2 Função reescrita
create or replace function public.consumir_rate_limit(
  p_chave  text,
  p_limite integer,
  p_janela interval
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_identidade text;
  v_contagem   integer;
begin
  v_identidade := public.identidade_requisicao();

  -- Faxina: descarta o que já não conta para janela nenhuma.
  delete from public.seguranca_rate_limit
  where ocorrido_em < now() - interval '1 day';

  -- Registra a tentativa atual.
  insert into public.seguranca_rate_limit (chave, identidade)
  values (p_chave, v_identidade);

  -- Conta as tentativas dentro da janela deslizante, incluindo esta.
  select count(*) into v_contagem
  from public.seguranca_rate_limit r
  where r.chave = p_chave
    and r.identidade = v_identidade
    and r.ocorrido_em > now() - p_janela;

  -- coalesce blinda contra o modo de falha silenciosa: se a contagem viesse
  -- NULL por qualquer motivo, o antigo `NULL <= limite` dava NULL e o `if not`
  -- não entrava no ramo, liberando tudo. Agora, na dúvida, bloqueia.
  return coalesce(v_contagem, p_limite + 1) <= p_limite;
end;
$$;

alter function public.consumir_rate_limit(text, integer, interval) owner to postgres;
revoke all on function public.consumir_rate_limit(text, integer, interval) from public, anon, authenticated;

-- 2.3 Teste automático de verdade: chama a função 7 vezes com limite 5
-- e confere que as duas últimas são recusadas.
do $$
declare
  v_ok       boolean;
  v_liberou  integer := 0;
  v_bloqueou integer := 0;
  i          integer;
begin
  delete from public.seguranca_rate_limit where chave = 'autoteste';

  for i in 1..7 loop
    v_ok := public.consumir_rate_limit('autoteste', 5, interval '1 hour');
    if v_ok then v_liberou := v_liberou + 1; else v_bloqueou := v_bloqueou + 1; end if;
  end loop;

  delete from public.seguranca_rate_limit where chave = 'autoteste';

  if v_liberou = 5 and v_bloqueou = 2 then
    raise notice 'OK: rate limit funcionando (5 liberadas, 2 bloqueadas em 7 tentativas).';
  else
    raise warning 'FALHA: esperado 5 liberadas e 2 bloqueadas, obtive % e %.',
      v_liberou, v_bloqueou;
  end if;
end;
$$;

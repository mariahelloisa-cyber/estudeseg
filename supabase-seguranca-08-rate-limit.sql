-- 1.1 O que foi parar na tabela de contadores?
-- Se vier vazia: a função nem está gravando (candidato a ou b).
-- Se vier com várias linhas de contagem = 1: está gravando mas não
-- incrementando (candidato b ou c) — repare se a coluna identidade varia.
select chave, identidade, janela, contagem
from public.seguranca_rate_limit
order by janela desc, chave
limit 30;

-- 1.2 Dono da tabela, RLS e FORCE
select
  c.relname                     as tabela,
  pg_get_userbyid(c.relowner)   as dono,
  c.relrowsecurity              as rls,
  c.relforcerowsecurity         as rls_forcada,
  (select count(*) from pg_policies p
    where p.schemaname = 'public' and p.tablename = c.relname) as policies
from pg_class c
join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relname = 'seguranca_rate_limit';

-- 1.3 O dono das funções tem BYPASSRLS? (decide se o candidato (a) procede)
select rolname, rolsuper, rolbypassrls
from pg_roles
where rolname in ('postgres', 'authenticator', 'supabase_admin');


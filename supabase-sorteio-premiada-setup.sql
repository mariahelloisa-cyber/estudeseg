create table if not exists public.sorteio_premios (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nome text not null,
  tipo text not null default 'cashback' check (tipo in ('cashback', 'desconto', 'curso')),
  percentual_cashback numeric,
  peso integer not null default 1 check (peso >= 0),
  ativo boolean not null default true,
  ordem integer not null default 0
);

alter table public.sorteio_premios enable row level security;


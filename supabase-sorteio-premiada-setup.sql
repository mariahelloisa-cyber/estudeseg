-- ============================================================
-- 5) FUNÇÃO: girar_roleta_premiada
-- ============================================================
-- Faz tudo atomicamente, no servidor: confere se já participou, confere
-- elegibilidade (matriculados.status_order = 7, "Certificado concluído"),
-- sorteia o prêmio por peso de probabilidade e grava a participação.
-- resultado possíveis: 'ja_participou' | 'sucesso' | 'nao_encontrado' | 'campanha_inativa' | 'sem_premios'
drop function if exists public.girar_roleta_premiada(text, text, text);
create or replace function public.girar_roleta_premiada(
  p_nome_completo text,
  p_cpf text,
  p_numero_matricula text
)
returns table (
  resultado text,
  premio_nome text,
  premio_tipo text,
  percentual_cashback numeric,
  data_sorteio timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_cpf_normalizado text := regexp_replace(coalesce(p_cpf, ''), '\D', '', 'g');
  v_matriculado record;
  v_participacao record;
  v_premio record;
  v_total_peso integer;
  v_sorteio numeric;
  v_acumulado integer := 0;
  v_ip text;
  v_user_agent text;
begin
  -- Cabeçalhos reais da requisição HTTP (a chamada via supabase.rpc() passa pelo
  -- PostgREST, que expõe os headers originais aqui). Só para registro/estatística.
  begin
    v_ip := coalesce(
      split_part(current_setting('request.headers', true)::json ->> 'x-forwarded-for', ',', 1),
      null
    );
    v_user_agent := current_setting('request.headers', true)::json ->> 'user-agent';
  exception when others then
    v_ip := null;
    v_user_agent := null;
  end;

  -- 1) já participou com esse CPF?
  select * into v_participacao
  from public.sorteio_participantes
  where cpf = v_cpf_normalizado
  limit 1;

  if found then
    return query select 'ja_participou'::text, v_participacao.premio, v_participacao.premio_tipo,
      v_participacao.percentual_cashback, v_participacao.data_sorteio;
    return;
  end if;

  -- 2) campanha ativa?
  if coalesce((select valor from public.configuracoes where chave = 'sorteio_ativo'), 'true') = 'false' then
    return query select 'campanha_inativa'::text, null::text, null::text, null::numeric, null::timestamptz;
    return;
  end if;

  -- 3) elegível? nome + cpf + número de matrícula/certificado batem e status = certificado concluído
  select * into v_matriculado
  from public.matriculados m
  where lower(trim(m.nome_completo)) = lower(trim(p_nome_completo))
    and regexp_replace(m.cpf, '\D', '', 'g') = v_cpf_normalizado
    and lower(trim(m.numero_matricula)) = lower(trim(coalesce(p_numero_matricula, '')))
    and m.status_order = 7
  limit 1;

  if not found then
    return query select 'nao_encontrado'::text, null::text, null::text, null::numeric, null::timestamptz;
    return;
  end if;

  -- 4) sorteio ponderado entre os prêmios ativos
  select coalesce(sum(peso), 0) into v_total_peso from public.sorteio_premios where ativo = true;
  if v_total_peso <= 0 then
    return query select 'sem_premios'::text, null::text, null::text, null::numeric, null::timestamptz;
    return;
  end if;

  v_sorteio := random() * v_total_peso;

  for v_premio in select * from public.sorteio_premios where ativo = true order by ordem asc, id asc loop
    v_acumulado := v_acumulado + v_premio.peso;
    if v_sorteio <= v_acumulado then
      exit;
    end if;
  end loop;

  -- 5) grava a participação — a constraint unique(cpf) impede corrida (2 giros simultâneos)
  begin
    insert into public.sorteio_participantes
      (nome, cpf, numero_matricula, matriculado_id, premio, premio_tipo, percentual_cashback, ip, user_agent)
    values
      (trim(p_nome_completo), v_cpf_normalizado, trim(p_numero_matricula), v_matriculado.id,
       v_premio.nome, v_premio.tipo, v_premio.percentual_cashback, v_ip, v_user_agent);
  exception when unique_violation then
    select * into v_participacao from public.sorteio_participantes where cpf = v_cpf_normalizado limit 1;
    return query select 'ja_participou'::text, v_participacao.premio, v_participacao.premio_tipo,
      v_participacao.percentual_cashback, v_participacao.data_sorteio;
    return;
  end;

  return query select 'sucesso'::text, v_premio.nome, v_premio.tipo, v_premio.percentual_cashback, now();
end;
$$;

grant execute on function public.girar_roleta_premiada(text, text, text) to anon, authenticated;
